-- Run this in Supabase SQL Editor. Keep Row Level Security enabled.
create table if not exists public.printing_jobs (
 id uuid primary key default gen_random_uuid(),
 job_code text unique,
 customer_name text not null,
 model_name text not null,
 material text not null default 'PLA',
 color text,
 weight_grams numeric(10,2) not null check(weight_grams > 0),
 rate_per_gram numeric(10,2) not null default 0 check(rate_per_gram >= 0),
 amount numeric(12,2) not null default 0 check(amount >= 0),
 due_date date,
 status text not null default 'Queued' check(status in ('Queued','Printing','Completed','Failed','Cancelled')),
 notes text,
 created_by uuid references auth.users(id),
 created_at timestamptz not null default now(),
 deleted boolean not null default false
);
create index if not exists printing_jobs_created_at_idx on public.printing_jobs(created_at desc);
alter table public.printing_jobs enable row level security;
drop policy if exists "Authenticated users can read printing jobs" on public.printing_jobs;
drop policy if exists "Authenticated users can create printing jobs" on public.printing_jobs;
drop policy if exists "Authenticated users can update printing jobs" on public.printing_jobs;
create policy "Authenticated users can read printing jobs" on public.printing_jobs for select to authenticated using (true);
create policy "Authenticated users can create printing jobs" on public.printing_jobs for insert to authenticated with check (auth.uid() = created_by);
create policy "Authenticated users can update printing jobs" on public.printing_jobs for update to authenticated using (true) with check (true);
-- Job code is generated by this trigger, e.g. 3DP-00001
create or replace function public.set_printing_job_code() returns trigger language plpgsql as $$
begin if new.job_code is null then new.job_code := '3DP-' || lpad(nextval('public.printing_job_code_seq')::text,5,'0'); end if; return new; end; $$;
create sequence if not exists public.printing_job_code_seq start 1;
drop trigger if exists printing_job_code_trigger on public.printing_jobs;
create trigger printing_job_code_trigger before insert on public.printing_jobs for each row execute function public.set_printing_job_code();
